#  6. Downloads
# ---------------------------------------------------------------------------


def render_downloads(run: Any, *, config: Any = None, audit: Any = None) -> None:
    st = _st()
    st.subheader("Downloads")
    st.caption(
        "Downloads are produced by the same exporters as the CLI: CSV tables, "
        "figures, report.md/report.html and the GeoPackage with its SHA-256 manifest."
    )

    if st.button("Prepare download bundle"):
        from rts_forensics import gis, report

        out_dir = Path(tempfile.mkdtemp(prefix="rts-forensics-"))
        try:
            report.write_tables(run, out_dir)
            report.plot_results(run, out_dir)
            report.render_report(run, out_dir)
            gis.write_geopackage(run, out_dir / "rts_forensics.gpkg", config=config)
        except Exception as exc:  # surface exporter errors in the UI, never crash the app
            st.error(f"Export failed: {exc}")
        else:
            st.session_state["rts_forensics_download_dir"] = str(out_dir)

    out_dir_value = (
        st.session_state["rts_forensics_download_dir"]
        if "rts_forensics_download_dir" in st.session_state
        else None
    )
    if not out_dir_value:
        st.info("Select 'Prepare download bundle' to generate the outputs.")
        return

    files = sorted(path for path in Path(out_dir_value).rglob("*") if path.is_file())
    if not files:
        st.warning("The exporter produced no files.")
        return
    for path in files:
        st.download_button(
            label=f"{path.relative_to(out_dir_value)} ({path.stat().st_size:,} bytes)",
            data=path.read_bytes(),
            file_name=path.name,
            key=f"download::{path}",
        )


