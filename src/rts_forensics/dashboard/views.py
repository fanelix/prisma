#  2. Station frame
# ---------------------------------------------------------------------------


def render_station_frame(run: Any, *, config: Any = None, audit: Any = None) -> None:
    st = _st()
    st.subheader("Station frame")
    st.caption(
        "Per-cycle frame reconstruction. Raw observations are never overwritten; "
        "the fitted correction is experimental and relative to the chosen network."
    )

    st.markdown("**Station cycles**")
    _show_table(
        st,
        _cycle_table(run),
        caption="Times, counts, station coordinates, orientation offset and scale.",
        message="No station cycle table is available.",
    )

    coefficients = _frame_coefficients(run)
    st.markdown("**Frame coefficients**")
    _show_table(
        st,
        coefficients,
        caption="Rotation/translation/scale/vertical terms with standard errors and rank.",
        message="Frame coefficients are not available (frame correction not configured or insufficient).",
    )

    if _exists(coefficients, "cycle_id", "rotation_arcsec"):
        st.markdown("**Rotation and translation through the record**")
        y_columns = _chart_columns(
            coefficients, ("rotation_arcsec", "tE_mm", "tN_mm", "scale_ppm")
        )
        if y_columns:
            st.line_chart(coefficients, x="cycle_id", y=y_columns)

    diagnostics = _frame_diagnostics(run)
    st.markdown("**Fit diagnostics (rank, conditioning, RMS)**")
    _show_table(st, diagnostics, message="No frame diagnostics are available.")

    membership = _frame_membership(run)
    st.markdown("**Frame membership and exclusions**")
    _show_table(
        st,
        membership,
        caption="Exclusions prevent a tested point from proving its own stability.",
        message="Frame membership is not published in this run.",
    )

    corrected = _frame_corrected(run)
    st.markdown("**Raw versus frame-corrected series**")
    if _exists(corrected, "los_raw_mm", "los_fc_mm"):
        pairs = _chart_columns(
            corrected,
            ("los_raw_mm", "los_fc_mm", "ver_raw_mm", "ver_fc_mm", "tan_raw_mm", "tan_fc_mm"),
        )
        st.caption(
            "Both raw and corrected columns are shown; the corrected series is "
            "experimental and must be read beside the raw one."
        )
        st.line_chart(corrected, x="cycle_id", y=pairs)
        st.dataframe(corrected.head(500), use_container_width=True)
    else:
        _show_table(st, corrected, message="No frame-corrected series is available.")


# ---------------------------------------------------------------------------
#  3. Prism explorer
# ---------------------------------------------------------------------------


def render_prism_explorer(run: Any, *, config: Any = None, audit: Any = None) -> None:
    st = _st()
    st.subheader("Prism explorer")
    point_ids = _point_ids(run)
    if not point_ids:
        st.info("No prism-cycle series are available in this run.")
        return

    point_id = st.selectbox("Prism", point_ids)
    concern = _filtered(_table(run, "concern"), point_id)
    reliability = _filtered(_table(run, "reliability"), point_id)

    left, right = st.columns(2)
    with left:
        st.markdown("**Movement concern (exploratory screening)**")
        _show_table(
            st,
            concern,
            message="No movement-concern row for this prism.",
            limit=100,
        )
    with right:
        st.markdown("**Measurement reliability (separate from concern)**")
        _show_table(
            st,
            reliability,
            message="No reliability row for this prism.",
            limit=100,
        )

    st.markdown("**Raw versus frame-corrected series**")
    corrected = _filtered(_table(run, "frame_corrected"), point_id)
    if _exists(corrected, "cycle_id", "los_raw_mm", "los_fc_mm"):
        y_columns = _chart_columns(
            corrected,
            ("los_raw_mm", "los_fc_mm", "ver_raw_mm", "ver_fc_mm", "tan_raw_mm", "tan_fc_mm"),
        )
        st.caption(
            "Frame correction is experimental and relative to the chosen network; "
            "raw and corrected series are plotted together, never one instead of the other."
        )
        st.line_chart(corrected, x="cycle_id", y=y_columns)
        st.dataframe(corrected, use_container_width=True)
    else:
        displacements = _filtered(_table(run, "displacements"), point_id)
        st.caption("Frame correction is not available for this run; raw products are shown.")
        _show_table(st, displacements, message="No displacement series for this prism.")

    st.markdown("**Rates (24 h block medians, backwards from the final record)**")
    rates = _filtered(_table(run, "rates"), point_id)
    _show_table(st, rates, message="No rate rows for this prism.")

    st.markdown("**Retained flags (never deleted)**")
    flags = _filtered(_table(run, "flags"), point_id)
    if _empty(flags):
        flags = _filtered(_table(run, "spikes"), point_id)
    _show_table(st, flags, message="No retained flags for this prism.")


