def render_upload_audit(run: Any, *, config: Any = None, audit: Any = None) -> None:
    st = _st()
    st.subheader("Upload & audit")
    st.caption(
        "The original upload is never modified. Every derived row keeps its "
        "source SHA-256 and physical line number."
    )

    parsed = getattr(run, "parsed", None)
    sources = getattr(parsed, "sources", None) or []
    if sources:
        st.markdown("**Source files (original bytes and SHA-256)**")
        st.dataframe(
            [
                {
                    "name": source.name,
                    "sha256": source.sha256,
                    "bytes": source.n_bytes,
                    "rows": source.n_rows,
                }
                for source in sources
            ],
            use_container_width=True,
        )

    spec = getattr(parsed, "format", None)
    if spec is not None:
        st.markdown("**Detected format**")
        st.json(
            {
                "delimiter": spec.delimiter,
                "encoding": spec.encoding,
                "time_format": spec.time_format,
                "has_header": spec.has_header,
            }
        )

    diagnostics = getattr(parsed, "diagnostics", None)
    st.markdown("**Parser diagnostics**")
    _show_table(
        st,
        diagnostics,
        message="No parser diagnostics were recorded.",
    )

    observations = _observations(run)
    if not _empty(observations):
        st.markdown(f"**Canonical observations** ({len(observations):,} rows)")
        st.dataframe(observations.head(200), use_container_width=True)

    if audit is not None:
        summary = audit.summary() if hasattr(audit, "summary") else {}
        st.markdown("**Configuration audit**")
        st.json(summary)
        warnings = getattr(audit, "warnings", None) or []
        for warning in warnings:
            st.warning(warning)

    st.markdown("**Effective configuration**")
    if config is not None and hasattr(config, "to_dict"):
        st.json(config.to_dict())
    else:
        st.info("No configuration object is attached to this run.")


