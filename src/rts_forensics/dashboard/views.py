def _coordinate_table(run: Any) -> Any:
    for name in ("prism_summary", "prism_cycles", "observations"):
        table = _table(run, name)
        if _exists(table, "te_m", "tn_m"):
            return table
    return None


def render_map(run: Any, *, config: Any = None, audit: Any = None) -> None:
    st = _st()
    st.subheader("Map")
    st.caption(
        "Drawn in the supplied Cartesian grid. Easting/northing are processing "
        "coordinates and may be a shifted dummy grid; no CRS is inferred and no "
        "geographic basemap is requested."
    )

    coordinates = _coordinate_table(run)
    if coordinates is None:
        st.info("No coordinate table is available in this run.")
        return

    frame = coordinates.dropna(subset=["te_m", "tn_m"])
    summary = _table(run, "prism_summary")
    color = None
    if _exists(summary, "point_id", "final_class"):
        frame = frame.merge(
            summary[["point_id", "final_class"]],
            on="point_id",
            how="left",
        ) if "point_id" in frame.columns else frame
        color = "final_class"
    if color is not None and color in frame.columns:
        st.scatter_chart(frame, x="te_m", y="tn_m", color=color)
    else:
        st.scatter_chart(frame, x="te_m", y="tn_m")

    if _transform_configured(config):
        gis_config = config.gis
        st.info(
            "A site transform/CRS is configured: exported geometry (and vector "
            "components) follow it. The preview above stays in the input grid; "
            "no basemap is added."
        )
        st.json(
            {
                "srs_id": gis_config.srs_id,
                "srs_wkt": gis_config.srs_wkt,
                "transform": gis_config.transform,
            }
        )
    else:
        st.caption(
            "No transform/CRS is configured (srs_id -1, undefined Cartesian), so "
            "no basemap is drawn and none is implied."
        )

    show_vectors = st.checkbox("Show movement-vector attributes (if exported)")
    if show_vectors:
        vectors = _table(run, "movement_vectors")
        _show_table(
            st,
            vectors,
            caption="Vector role (raw / frame-corrected / artefact) and contributing interval are explicit.",
            message="Movement vectors are written to the GeoPackage download; no in-run vector table is registered.",
        )

    st.markdown("**Coordinates used for the plot**")
    st.dataframe(frame.head(2000), use_container_width=True)


# ---------------------------------------------------------------------------
#  5. Events & investigations
# ---------------------------------------------------------------------------


def render_events(run: Any, *, config: Any = None, audit: Any = None) -> None:
    st = _st()
    st.subheader("Events & investigations")
    st.caption(
        "Candidate events and investigation records. Every candidate carries "
        "competing explanations; correlation alone does not identify a resection "
        "reference."
    )

    forensics = getattr(run, "forensics", None)
    evidence = getattr(forensics, "evidence", None) or {}
    if evidence:
        families = list(evidence)
        tabs = st.tabs(families)
        for tab, family in zip(tabs, families, strict=True):
            with tab:
                _show_table(st, evidence[family], message=f"No evidence rows for {family}.")
    else:
        st.info("No forensic evidence tables are registered in this run.")

    investigations = getattr(forensics, "investigations", None)
    st.markdown("**Investigation register**")
    _show_table(st, investigations, message="No investigation records.")

    statuses = getattr(forensics, "statuses", None)
    st.markdown("**Test statuses (unavailable tests carry an explicit reason)**")
    _show_table(st, statuses, message="No per-test status table.")

    events = _table(run, "candidate_events")
    st.markdown("**Candidate frame events from cycle processing**")
    _show_table(st, events, message="No candidate frame events detected.")


