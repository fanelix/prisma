"""
views.py — one renderer per dashboard page.

Design constraints:

* Streamlit is imported lazily inside each renderer, so importing
  :mod:`rts_forensics.dashboard.views` (and therefore
  :mod:`rts_forensics.dashboard`) works without Streamlit installed.
* Renderers only read the :class:`~rts_forensics.models.RunResult` produced by
  :func:`rts_forensics.pipeline.run_analysis` and, for exports, call the public
  exporter APIs ``rts_forensics.report.write_tables`` / ``plot_results`` /
  ``render_report`` and ``rts_forensics.gis.write_geopackage``; downloads are
  generated by exactly the same exporters as the CLI.
* Raw and frame-corrected series are always shown side by side.
* Movement concern and measurement reliability are rendered as separate
  sections; they are never merged into one grade.
* The map is drawn in the supplied Cartesian grid. No geographic basemap is
  requested, and none is drawn unless a site transform/CRS is configured.
"""

from __future__ import annotations

import tempfile
from collections.abc import Callable, Iterable
from pathlib import Path
from typing import Any

# ---------------------------------------------------------------------------
#  Lazy Streamlit access and small display helpers
# ---------------------------------------------------------------------------


def _st() -> Any:
    """Import Streamlit at call time, never at module import time."""
    import streamlit as st

    return st


def _table(run: Any, name: str) -> Any:
    """Fetch a registered table by canonical name, or ``None``."""
    tables = getattr(run, "tables", None) or {}
    if name in tables:
        return tables[name]
    getter = _TABLE_GETTERS.get(name)
    return getter(run) if getter is not None else None


def _empty(table: Any) -> bool:
    return table is None or bool(getattr(table, "empty", True))


def _show_table(
    st: Any,
    table: Any,
    *,
    caption: str | None = None,
    message: str = "No rows are available for this table in the current run.",
    limit: int | None = 500,
) -> None:
    if caption:
        st.caption(caption)
    if _empty(table):
        st.info(message)
        return
    view = table.head(limit) if limit is not None else table
    st.dataframe(view, use_container_width=True)


def _filtered(table: Any, point_id: str) -> Any:
    if _empty(table) or "point_id" not in getattr(table, "columns", ()):
        return table
    return table[table["point_id"] == point_id]


def _point_ids(run: Any) -> list[str]:
    for name in ("prism_summary", "concern", "reliability", "frame_corrected", "displacements"):
        table = _table(run, name)
        if not _empty(table) and "point_id" in table.columns:
            return sorted(str(value) for value in table["point_id"].dropna().unique())
    observations = _table(run, "observations")
    if not _empty(observations) and "point_id" in observations.columns:
        return sorted(str(value) for value in observations["point_id"].dropna().unique())
    return []


def _exists(table: Any, *columns: str) -> bool:
    available = getattr(table, "columns", ())
    return not _empty(table) and all(column in available for column in columns)


def _chart_columns(table: Any, candidates: Iterable[str]) -> list[str]:
    available = getattr(table, "columns", ())
    return [column for column in candidates if column in available]


def _transform_configured(config: Any) -> bool:
    if config is None:
        return False
    gis_config = getattr(config, "gis", None)
    if gis_config is None:
        return False
    return bool(getattr(gis_config, "transform", None)) or bool(getattr(gis_config, "srs_wkt", None))


# ---------------------------------------------------------------------------
#  RunResult accessors (the run keeps both section objects and a table registry)
# ---------------------------------------------------------------------------


def _observations(run: Any) -> Any:
    return getattr(run, "observations", None)


def _cycle_table(run: Any) -> Any:
    cycles = getattr(run, "cycles", None)
    return getattr(cycles, "cycles", None)


def _segments(run: Any) -> Any:
    cycles = getattr(run, "cycles", None)
    return getattr(cycles, "segments", None)


def _candidate_events(run: Any) -> Any:
    cycles = getattr(run, "cycles", None)
    return getattr(cycles, "candidate_events", None)


def _prism_cycles(run: Any) -> Any:
    displacements = getattr(run, "displacements", None)
    return getattr(displacements, "prism_cycles", None)


def _baselines(run: Any) -> Any:
    displacements = getattr(run, "displacements", None)
    return getattr(displacements, "baselines", None)


def _displacements(run: Any) -> Any:
    displacements = getattr(run, "displacements", None)
    return getattr(displacements, "displacements", None)


def _noise_pooled(run: Any) -> Any:
    noise = getattr(run, "noise", None)
    return getattr(noise, "pooled", None)


def _noise_flags(run: Any) -> Any:
    noise = getattr(run, "noise", None)
    return getattr(noise, "flags", None)


def _frame_coefficients(run: Any) -> Any:
    frames = getattr(run, "frames", None)
    return getattr(frames, "coefficients", None)


def _frame_diagnostics(run: Any) -> Any:
    frames = getattr(run, "frames", None)
    return getattr(frames, "diagnostics", None)


def _frame_corrected(run: Any) -> Any:
    frames = getattr(run, "frames", None)
    return getattr(frames, "corrected", None)


def _frame_membership(run: Any) -> Any:
    frames = getattr(run, "frames", None)
    selection = getattr(frames, "membership", None)
    return getattr(selection, "diagnostics", None)


def _rates(run: Any) -> Any:
    rates = getattr(run, "rates", None)
    if not _empty(rates):
        return rates
    return _table_from_tables(run, "rates")


def _concern(run: Any) -> Any:
    classification = getattr(run, "classification", None)
    return getattr(classification, "concern", None)


def _reliability(run: Any) -> Any:
    classification = getattr(run, "classification", None)
    return getattr(classification, "reliability", None)


def _flags(run: Any) -> Any:
    classification = getattr(run, "classification", None)
    return getattr(classification, "flags", None)


def _summary(run: Any) -> Any:
    table = _table_from_tables(run, "prism_summary")
    if table is not None:
        return table
    return _table_from_tables(run, "summary")


def _table_from_tables(run: Any, name: str) -> Any:
    return (getattr(run, "tables", None) or {}).get(name)


_TABLE_GETTERS: dict[str, Callable[[Any], Any]] = {
    "observations": _observations,
    "prism_cycles": _prism_cycles,
    "baselines": _baselines,
    "displacements": _displacements,
    "segments": _segments,
    "processing_segments": _segments,
    "candidate_events": _candidate_events,
    "rates": _rates,
    "pooled_repeatability": _noise_pooled,
    "noise_pooled": _noise_pooled,
    "spikes": _noise_flags,
    "frame_cycles": _frame_coefficients,
    "frame_coefficients": _frame_coefficients,
    "frame_diagnostics": _frame_diagnostics,
    "frame_membership": _frame_membership,
    "frame_corrected": _frame_corrected,
    "timeseries_24h": lambda run: _table_from_tables(run, "timeseries_24h"),
    "concern": _concern,
    "reliability": _reliability,
    "flags": _flags,
    "prism_summary": _summary,
    "summary": _summary,
}


